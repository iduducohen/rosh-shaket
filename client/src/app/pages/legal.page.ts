export function legalDoc(kind: 'terms' | 'privacy'): LegalDoc {
  return kind === 'privacy' ? PRIVACY : TERMS;
}

@Component({
  selector: 'app-legal',
  standalone: true,
  imports: [IonContent, RouterLink],
  styles: [`
    article { max-width: 720px; margin: 0 auto; padding-bottom: 64px; }
    h1 { font-family: var(--rs-serif); font-size: 36px; margin: 8px 0 4px; }
    h2 { font-size: 20px; margin: 28px 0 8px; }
    p { line-height: 1.7; margin: 0 0 10px; }
    .back, .more a { font-weight: 700; }
    .more { margin-top: 28px; }
  `],
  template: `
    <ion-content>
      <article class="ion-padding">
        <a class="back" routerLink="/">לדף הבית</a>
        <h1>{{ doc().title }}</h1>
        <p class="muted small">עודכן לאחרונה: {{ doc().updated }}</p>
        @for (section of doc().sections; track section.heading) {
          <h2>{{ section.heading }}</h2>
          @for (paragraph of section.paragraphs; track $index) {
            <p>{{ paragraph }}</p>
          }
        }
        <p class="more"><a [routerLink]="doc().otherPath">{{ doc().otherLabel }}</a></p>
      </article>
    </ion-content>
  `
})
export class LegalPage {
  private readonly route = inject(ActivatedRoute);
  private readonly kind = toSignal(this.route.data.pipe(map(data => data['doc'] as string)), { initialValue: 'terms' });
  readonly doc = computed(() => legalDoc(this.kind() === 'privacy' ? 'privacy' : 'terms'));
}
